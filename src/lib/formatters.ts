// নামের প্রথম দুটি অক্ষর ক্যাপিটাল লেটারে বের করার ফাংশন
export const getInitials = (name?: string): string => {
  if (!name) return "U"; // নাম না থাকলে ডিফল্ট "U" দেখাবে
  return name
    .split(" ") // স্পেস দিয়ে শব্দগুলো আলাদা করা হচ্ছে
    .map((n) => n[0]) // প্রতি শব্দের প্রথম অক্ষর নেওয়া হচ্ছে
    .join("") // সব অক্ষর একসাথে জোড়া লাগানো হচ্ছে
    .toUpperCase() // বড় হাতের অক্ষরে রূপান্তর করা হচ্ছে
    .slice(0, 2); // প্রথম ২ টি অক্ষর নেওয়া হচ্ছে
};
